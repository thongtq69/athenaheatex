/* Build stable Vietnamese visitor URLs without changing MongoDB page keys. */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { load } from 'cheerio';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dist = path.join(root, 'dist');
const special = {
  '/machinery-2.html': '/may-moc',
  '/complete-line-1.html': '/day-chuyen-hoan-chinh',
  '/solution-3.html': '/giai-phap',
  '/service-4.html': '/dich-vu',
  '/news-67.html': '/tin-tuc',
  '/about-us-6.html': '/gioi-thieu',
  '/contact-us-7.html': '/lien-he',
  '/search.html': '/tim-kiem',
};
const slug = value => String(value || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').replace(/Đ/g, 'D').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 72).replace(/-+$/g, '');
const index = JSON.parse(await readFile(path.join(root, 'reports', 'search-index.json'), 'utf8'));
const titles = new Map(index.map(item => [item.path, item.title]));
const files = (await readdir(dist)).filter(name => name.endsWith('.html')).sort();
const paths = {};
const used = new Set(Object.values(special));

for (const file of files) {
  const source = '/' + file;
  if (source === '/index.html' || source === '/404.html') continue;
  if (special[source]) { paths[source] = special[source]; continue; }
  const $ = load(await readFile(path.join(dist, file), 'utf8'));
  const title = titles.get(source) || $('#location a').last().text().trim() || $('title').first().text().split('-')[0].trim() || file.replace(/\.html$/, '');
  const pagination = file.match(/^(\d+)_(\d+)\.html$/);
  const numbered = file.match(/-(\d+)\.html$/);
  const base = slug(title) || slug(file.replace(/\.html$/, ''));
  let visitor = '/' + (pagination ? `${base}-trang-${pagination[2]}` : numbered ? `${base}-${numbered[1]}` : base);
  if (used.has(visitor)) visitor += '-' + slug(file.replace(/\.html$/, ''));
  if (used.has(visitor)) throw new Error(`Trùng URL tiếng Việt: ${source} → ${visitor}`);
  used.add(visitor);
  paths[source] = visitor;
}

const sorted = Object.fromEntries(Object.entries(paths).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(path.join(root, 'lib', 'public-path-map.mjs'), `// Generated by scripts/generate-public-paths.mjs. Do not edit by hand.\nexport const PUBLIC_PATHS = Object.freeze(${JSON.stringify(sorted, null, 2)});\n`);
await writeFile(path.join(dist, 'public-paths.json'), JSON.stringify(sorted));
await writeFile(path.join(dist, 'search-index.json'), JSON.stringify(index.map(item => ({ ...item, path: sorted[item.path] || item.path }))));

// Vercel removes the mirrored HTML and serves pages from MongoDB through the
// render function. Every friendly path therefore needs an explicit rewrite.
// Keep old links usable with permanent redirects; both lists are generated
// from the same map so they cannot drift apart.
const config = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  buildCommand: 'npm run build && node scripts/prune-vercel-html.mjs',
  outputDirectory: 'dist',
  framework: null,
  redirects: [
    ...Object.entries(sorted).map(([source, destination]) => ({ source, destination, permanent: true })),
    { source: '/languages/vi', destination: '/', permanent: true },
    { source: '/languages/vi/:path*', destination: '/:path*', permanent: true },
    { source: '/languages/:lang', destination: '/', permanent: true },
    { source: '/languages/:lang/:path*', destination: '/', permanent: true },
    { source: '/index.php', destination: '/tim-kiem', permanent: false },
    { source: '/search.php', destination: '/tim-kiem', permanent: false },
  ],
  rewrites: [
    { source: '/api/admin/:path*', destination: '/api/admin?path=:path*' },
    { source: '/', destination: '/api/render?path=/index.html' },
    ...Object.entries(sorted).map(([source, visitor]) => ({ source: visitor, destination: `/api/render?path=${source}` })),
    { source: '/:page*.html', destination: '/api/render?path=/:page*.html' },
  ],
};
await writeFile(path.join(root, 'vercel.json'), JSON.stringify(config, null, 2) + '\n');
console.log(`Generated ${Object.keys(sorted).length} Vietnamese public URLs.`);
